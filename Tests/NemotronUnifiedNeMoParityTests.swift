    private var modelPath: String? {
        let env = ProcessInfo.processInfo.environment
        guard env["MLXAUDIO_ENABLE_MLX_RUNTIME_TESTS"] == "1" else { return nil }
        return env["NEMOTRON_UNIFIED_MLX_PATH"]
    }

    private func edits(_ a: [Int], _ b: [Int]) -> Int {
        var prev = Array(0...b.count)
        for (i, x) in a.enumerated() {
            var cur = [i + 1]
            for (j, y) in b.enumerated() {
                cur.append(min(prev[j + 1] + 1, cur[j] + 1, prev[j] + (x == y ? 0 : 1)))
            }
            prev = cur
        }
        return prev[b.count]
    }

    @Test(arguments: [DType.float32, DType.bfloat16])
    func streamingTokensMatchNeMo(_ dtype: DType) throws {
        guard let modelPath, !Self.nemoTokens.isEmpty else { return }
        let model = try NemotronASRModel.fromDirectory(URL(fileURLWithPath: modelPath), computeDType: dtype)
        let url = try #require(Bundle.module.url(forResource: "false-turn", withExtension: "wav", subdirectory: "media"))
        let (_, audio) = try loadAudioArray(from: url, sampleRate: 16000)
        let samples: [Float] = audio.asArray(Float.self)
        let tolerance = dtype == .float32 ? 0.0 : 0.03
        for latency in [160, 320, 560, 1120, 2080] {
            let expected = try #require(Self.nemoTokens["\(latency)"])
            let session = model.makeStreamSession(language: "en", chunkMs: latency)
            var i = 0
            while i < samples.count {
                let end = min(i + 1280, samples.count)
                _ = session.step(Array(samples[i..<end]))
                i = end
            }
            _ = session.finish()
            let rate = Double(edits(session.tokens, expected)) / Double(max(expected.count, 1))
            #expect(rate <= tolerance, "latency \(latency) ms: edit rate \(rate)")
        }
    }
